//! uBlock-Origin-style blocking without the extension, using Brave's adblock-rust.
//!
//! * Scriptlets (`##+js(...)`) and cosmetic selectors are resolved here once at
//!   startup and baked into the webview's initialization script.
//! * Procedural cosmetic filters (`:has-text`, `:upward`, `:remove()`, ...) are
//!   handed to `js/procedural.js` as JSON.
//! * Network rules are converted to WebKit content-blocker JSON (see
//!   `netfilter_linux.rs`), see [`content_rules`].

use crate::filters::LoadedList;
use adblock::lists::{FilterSet, ParseOptions, RuleTypes};
use adblock::resources::{PermissionMask, Resource};
use adblock::Engine;

/// Permission bit granted to uBO's own lists so they may use `trusted-*`
/// scriptlets. Must match TRUSTED_PERMISSION in scripts/build-scriptlets.mjs.
const TRUSTED_PERMISSION: u8 = 1;

/// Generated by scripts/build-scriptlets.mjs from uBlock Origin (GPL-3.0).
const UBO_SCRIPTLETS: &str = include_str!("../resources/ubo-scriptlets.json");

/// Pages the cosmetic/scriptlet rules are resolved for.
const TARGET_URLS: &[&str] = &["https://music.youtube.com/"];

pub struct Blocking {
    /// JS to run at document start (scriptlets + cosmetic CSS + procedural filters).
    pub init_script: String,
}

fn parse_options(trusted: bool, rule_types: RuleTypes) -> ParseOptions {
    ParseOptions {
        rule_types,
        permissions: if trusted {
            PermissionMask::from_bits(TRUSTED_PERMISSION)
        } else {
            PermissionMask::default()
        },
        ..ParseOptions::default()
    }
}

fn load_scriptlets() -> Vec<Resource> {
    match serde_json::from_str::<Vec<Resource>>(UBO_SCRIPTLETS) {
        Ok(r) => r,
        Err(e) => {
            log::error!("ubo-scriptlets.json is invalid: {e}");
            Vec::new()
        }
    }
}

pub fn build(lists: &[LoadedList], procedural_js: &str) -> Blocking {
    // --- cosmetic + scriptlet engine --------------------------------------
    let mut set = FilterSet::new(false);
    for l in lists {
        set.add_filter_list(l.text.clone(), parse_options(l.list.trusted, RuleTypes::All));
    }
    let mut engine = Engine::new_with_filter_set(set);
    let scriptlets = load_scriptlets();
    let n_scriptlets = scriptlets.len();
    if n_scriptlets == 0 {
        log::warn!(
            "no uBO scriptlets bundled: YouTube ad stripping is disabled. \
             Run `node scripts/build-scriptlets.mjs` and rebuild."
        );
    }
    engine.use_resources(scriptlets);

    let mut per_host = String::new();
    let mut n_selectors = 0;
    let mut n_procedural = 0;
    for url in TARGET_URLS {
        let host = url.trim_start_matches("https://").trim_end_matches('/');
        let res = engine.url_cosmetic_resources(url);
        n_selectors += res.hide_selectors.len();
        n_procedural += res.procedural_actions.len();

        let mut selectors: Vec<_> = res.hide_selectors.into_iter().collect();
        selectors.sort();
        let css = if selectors.is_empty() {
            String::new()
        } else {
            format!("{}{{display:none!important}}", selectors.join(",\n"))
        };
        let procedural: Vec<serde_json::Value> = res
            .procedural_actions
            .iter()
            .filter_map(|s| serde_json::from_str(s).ok())
            .collect();

        per_host.push_str(&format!(
            "if (location.hostname === {host}) {{\n\
             /* scriptlets */\n\
             try {{ (function () {{ var scriptletGlobals = {{}};\n{scripts}\n}})(); }} catch (e) {{ console.warn('[tubedesk] scriptlets', e); }}\n\
             /* cosmetic */\n\
             __tdCss({css});\n\
             __tdProcedural({procedural});\n\
             }}\n",
            host = serde_json::to_string(host).unwrap(),
            scripts = res.injected_script,
            css = serde_json::to_string(&css).unwrap(),
            procedural = serde_json::to_string(&procedural).unwrap(),
        ));
    }

    let init_script = format!(
        "(function () {{\n\
         if (window.top !== window) return;\n\
         function __tdCss(css) {{\n\
           if (!css) return;\n\
           const add = () => {{ const s = document.createElement('style'); s.id = 'tubedesk-cosmetic'; s.textContent = css; (document.head || document.documentElement).appendChild(s); }};\n\
           if (document.documentElement) add(); else document.addEventListener('DOMContentLoaded', add, {{ once: true }});\n\
         }}\n\
         {procedural_js}\n\
         {per_host}\
         }})();\n"
    );

    let stats = format!(
        "{} lists, {n_scriptlets} scriptlet resources, {n_selectors} cosmetic selectors, {n_procedural} procedural filters",
        lists.len()
    );
    log::info!("adblock: {stats}");

    Blocking { init_script }
}

/// Converts the lists' network rules to a WebKit content-blocker JSON array.
/// Slow-ish (parses all lists again in debug mode), so only call it when the
/// compiled filter is not cached.
pub fn content_rules(lists: &[LoadedList]) -> Option<String> {
    let mut net = FilterSet::new(true);
    for l in lists {
        net.add_filter_list(l.text.clone(), parse_options(l.list.trusted, RuleTypes::NetworkOnly));
    }
    let (rules, _used) = net.into_content_blocking().ok()?;
    log::info!("{} network rules converted for WebKit", rules.len());
    serde_json::to_string(&rules).ok()
}
